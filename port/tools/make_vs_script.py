"""Write re/run_vsfight.cmd: an unattended two-player VS Battle (Solo, P1 Jun vs P2 Heihachi)
on a fixed stage, with both players fighting (dashes, strings, launchers, blocks).

Xbox 360 TTT2 default layout: X = 1 (left punch), Y = 2 (right punch), A = 3 (left kick),
B = 4 (right kick), RB = tag. P1 starts on the left (forward = RIGHT), P2 on the right
(forward = LEFT). Menu path measured with port/tools/nav.py screenshots (2026-10-11):
title START x2, autosave notice A, Offline Mode (DOWN A), P2 connects (P2+LB), VS Battle
(DOWN DOWN A), both press START, P1 LEFT / P2 RIGHT, A, confirm A, Solo (RIGHT A) for both,
characters (A / P2+A), stage select by P2 (cursor starts on the random column; LEFT x
`--stage-steps` then A).

    python port/tools/make_vs_script.py [--stage-steps 1] [--fight-seconds 150]
    re\\run_vsfight.cmd run_vs1.txt            (extra settings: set them before calling)
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage-steps", type=int, default=1, help="P2+LEFT presses on the stage grid")
    ap.add_argument("--stage", default="", help="stage-grid moves instead, e.g. LEFT,LEFT,DOWN")
    ap.add_argument("--p1", default="", help="P1 cursor moves before picking, e.g. RIGHT,DOWN (starts on Jun)")
    ap.add_argument("--p2", default="", help="P2 cursor moves before picking (starts on Heihachi)")
    ap.add_argument("--fight-seconds", type=int, default=150)
    ap.add_argument("--out", default="run_vsfight.cmd", help="file name under re/")
    ap.add_argument("--tag", action="store_true", help="Tag battle (two fighters per side) instead of Solo")
    args = ap.parse_args()

    presses = []

    def at(ms, buttons, hold=150):
        presses.append(f"{ms}:{buttons}:{hold}")

    at(22000, "START"); at(28000, "START"); at(36000, "A")
    at(60000, "DOWN", 120); at(62000, "A"); at(63000, "P2+LB", 100)
    at(66000, "DOWN", 120); at(66600, "DOWN", 120); at(67600, "A")
    at(71000, "START"); at(71600, "P2+START"); at(72600, "LEFT", 120); at(73200, "P2+RIGHT", 120)
    at(74400, "A"); at(76400, "A")
    if args.tag:                                    # Tag is preselected: two fighters each
        at(84600, "A"); at(85800, "P2+A")
    else:
        at(84000, "RIGHT", 120); at(84600, "A"); at(85200, "P2+RIGHT", 120); at(85800, "P2+A")
    t = 87000
    for move in filter(None, args.p1.split(",")):
        at(t, move, 100); t += 400
    for move in filter(None, args.p2.split(",")):
        at(t, "P2+" + move, 100); t += 400
    at(t + 600, "A"); at(t + 1200, "P2+A")
    t += 1800
    if args.tag:                                    # partners: one step right of the first pick
        at(t, "RIGHT", 100); at(t + 400, "P2+RIGHT", 100)
        at(t + 1000, "A"); at(t + 1600, "P2+A")
        t += 2200
    t = max(t + 3400, 92000)
    stage = [m for m in args.stage.split(",") if m] or ["LEFT"] * args.stage_steps
    for move in stage:
        at(t, "P2+" + move, 120)
        t += 600
    at(t + 400, "P2+A")

    # The fight: loading + intros take ~15 s after the stage pick.
    t = t + 18000
    end = t + args.fight_seconds * 1000
    cycle = 0
    while t < end:
        # P1: dash in, 1,2 jab string, 3+4 low kick, back off. P2: block, 1,1,2, d/f+2 launcher.
        at(t, "RIGHT", 90); at(t + 140, "RIGHT", 90)
        at(t + 400, "X", 60); at(t + 560, "Y", 60)
        at(t + 900, "P2+LEFT", 400)
        at(t + 1400, "P2+X", 60); at(t + 1550, "P2+X", 60); at(t + 1700, "P2+Y", 60)
        at(t + 2100, "DOWN+A", 80)
        at(t + 2500, "P2+DOWN+LEFT+Y", 80)
        at(t + 2900, "LEFT", 300)
        if cycle % 3 == 2:
            at(t + 3300, "X+Y", 80)            # throw attempt
            at(t + 3400, "P2+A+B", 80)
        t += 4000
        cycle += 1

    script = ",".join(presses)
    lines = [
        "@echo off",
        "rem Generated by port/tools/make_vs_script.py - unattended two-player VS Battle fight.",
        "rem Log name = first argument; set extra TTT2_* variables before calling.",
        "rem TTT2_BUILD selects the build directory (default build-o1).",
        "if not defined TTT2_BUILD set TTT2_BUILD=build-o1",
        "set TTT2_GPU_HW=1",
        "set TTT2_AUTO_SIGNIN=B13EBABEBABEBABE",   # scripted runs: the original profile, no Select Profile
        "set TTT2_NET=loopback",                    # scripted runs never sign in to Steam
        "set TTT2_SAVE_ROOT=%LOCALAPPDATA%\\TTT2Recomp\\test_saves",
        "set TTT2_FRAMETIME=1",
        f"set TTT2_INPUT_SCRIPT={script}",
        'call "%~dp0..\\tools\\run_port.cmd" %TTT2_BUILD% "%~dp0%~1"',
        "",
    ]
    out = ROOT / "re" / args.out
    out.write_bytes("\r\n".join(lines).encode("ascii"))
    print(out, len(presses), "presses, script", len(script), "chars")


if __name__ == "__main__":
    main()
